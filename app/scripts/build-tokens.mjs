#!/usr/bin/env node
/**
 * Build Rectangle's design tokens into a single CSS file.
 *
 * Reads W3C-format JSON tokens from `../tokens/` and emits
 * `src/styles/tokens.generated.css` with:
 *   - `:root`                              — primitives + light semantic + type/spacing/radius/stroke/motion
 *   - `[data-theme="dark"]`                — dark semantic overrides (manual toggle)
 *   - `@media (prefers-color-scheme: dark) [data-theme="system"]` — same, when user chose "follow system"
 *
 * Run with `pnpm tokens:build`.
 */

import StyleDictionary from "style-dictionary";
import { mkdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const APP_ROOT = resolve(__dirname, "..");
const TOKENS_ROOT = resolve(APP_ROOT, "..", "tokens");
const OUT_DIR = resolve(APP_ROOT, "src/styles");
const OUT_FILE = resolve(OUT_DIR, "tokens.generated.css");
const TMP_LIGHT = resolve(OUT_DIR, ".tokens.light.css");
const TMP_DARK = resolve(OUT_DIR, ".tokens.dark.css");

mkdirSync(OUT_DIR, { recursive: true });

const PRIMITIVES = [
  `${TOKENS_ROOT}/color.primitives.json`,
  `${TOKENS_ROOT}/typography.json`,
  `${TOKENS_ROOT}/spacing.json`,
  `${TOKENS_ROOT}/radius.json`,
  `${TOKENS_ROOT}/stroke.json`,
  `${TOKENS_ROOT}/motion.json`,
];

/**
 * Light pass: emit everything (primitives + light semantic + scales) under :root.
 * Semantic tokens come out as `var()` references to primitives thanks to
 * `outputReferences: true`.
 */
const lightSD = new StyleDictionary({
  source: [...PRIMITIVES, `${TOKENS_ROOT}/color.semantic.light.json`],
  platforms: {
    css: {
      transformGroup: "css",
      files: [
        {
          destination: TMP_LIGHT,
          format: "css/variables",
          options: { selector: ":root", outputReferences: true },
        },
      ],
    },
  },
});

/**
 * Dark pass: emit primitives + dark semantic. We only use the semantic lines
 * from this output (primitives live in :root already, no need to duplicate).
 */
const darkSD = new StyleDictionary({
  source: [`${TOKENS_ROOT}/color.primitives.json`, `${TOKENS_ROOT}/color.semantic.dark.json`],
  platforms: {
    css: {
      transformGroup: "css",
      files: [
        {
          destination: TMP_DARK,
          format: "css/variables",
          options: { selector: "[data-theme=\"dark\"]", outputReferences: true },
        },
      ],
    },
  },
});

await lightSD.buildAllPlatforms();
await darkSD.buildAllPlatforms();

const lightCss = readFileSync(TMP_LIGHT, "utf8");
const darkCss = readFileSync(TMP_DARK, "utf8");

// Extract only the semantic theme-* lines from the dark output (indented declarations).
const darkThemeLines = darkCss
  .split("\n")
  .filter((line) => /^\s+--theme-/.test(line))
  .join("\n");

const header = `/**
 * Rectangle's — auto-generated design tokens.
 * Source: tokens/*.json in repo root.
 * Rebuild: pnpm tokens:build
 * DO NOT EDIT this file by hand.
 */

`;

const darkBlock = `
[data-theme="dark"] {
${darkThemeLines}
}
`;

const systemDarkBlock = `
@media (prefers-color-scheme: dark) {
  [data-theme="system"] {
${darkThemeLines
  .split("\n")
  .map((l) => (l ? `  ${l}` : l))
  .join("\n")}
  }
}
`;

writeFileSync(OUT_FILE, header + lightCss.trim() + "\n" + darkBlock + systemDarkBlock);

unlinkSync(TMP_LIGHT);
unlinkSync(TMP_DARK);

console.log(`✓ Tokens built → ${OUT_FILE}`);
