#!/usr/bin/env node
/**
 * Sticker collection → one texture atlas.
 *
 *   source:  /Images/Stickers/<collection>/<category>/NN-name.png  (transparent, ~1254 px)
 *   output:  public/textures/stickers/atlas.webp
 *            src/scenes/store/stickers.data.ts   (UV rect + aspect per sticker)
 *
 * Each sticker is trimmed to its die-cut edge, scaled to the size it is ever
 * seen at (they are 6–12 cm decals) and shelf-packed into a single 2048-wide
 * sheet, so every sticker in the shop renders from one texture in one draw
 * call. Fully transparent pixels are filled with the die-cut border colour
 * so texture filtering doesn't pull a dark fringe around the edges.
 *
 * Usage: node scripts/optimize-stickers.mjs
 */
import { mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const APP = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(APP, "..", "Images", "Stickers");
const OUT = join(APP, "public", "textures", "stickers");
const DATA = join(APP, "src", "scenes", "store", "stickers.data.ts");

const SHEET_W = 2048;
const PAD = 6;
/** Longest side of a square sticker in the atlas; elongated ones get more so their type stays legible. */
const BASE = 288;
const MAX_SIDE = 448;
const BORDER = { r: 247, g: 247, b: 243 };

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : /^\d\d-.*\.png$/.test(e.name) ? [join(dir, e.name)] : [],
  );
}

const files = walk(SRC).sort((a, b) => basename(a).localeCompare(basename(b)));
let sourceBytes = 0;
const items = [];
for (const file of files) {
  sourceBytes += statSync(file).size;
  const trimmed = await sharp(file).trim({ threshold: 2 }).toBuffer({ resolveWithObject: true });
  const { width, height } = trimmed.info;
  const aspect = width / height;
  // Same visual area for every sticker, capped so long logos don't eat the sheet.
  const k = Math.min(BASE / Math.sqrt(width * height), MAX_SIDE / Math.max(width, height));
  const w = Math.round(width * k);
  const h = Math.round(height * k);
  const { data } = await sharp(trimmed.data).resize(w, h, { kernel: "lanczos3" }).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  for (let i = 0; i < data.length; i += 4) {
    if (data[i + 3] === 0) {
      data[i] = BORDER.r;
      data[i + 1] = BORDER.g;
      data[i + 2] = BORDER.b;
    }
  }
  items.push({ name: basename(file, ".png"), w, h, aspect, data });
}

// Shelf packing, tallest first.
const order = [...items].sort((a, b) => b.h - a.h);
let x = PAD;
let y = PAD;
let shelf = 0;
for (const it of order) {
  if (x + it.w + PAD > SHEET_W) {
    x = PAD;
    y += shelf + PAD;
    shelf = 0;
  }
  it.x = x;
  it.y = y;
  x += it.w + PAD;
  shelf = Math.max(shelf, it.h);
}
const SHEET_H = Math.ceil((y + shelf + PAD) / 4) * 4;

mkdirSync(OUT, { recursive: true });
const out = join(OUT, "atlas.webp");
await sharp({ create: { width: SHEET_W, height: SHEET_H, channels: 4, background: { ...BORDER, alpha: 0 } } })
  .composite(items.map((it) => ({ input: it.data, raw: { width: it.w, height: it.h, channels: 4 }, left: it.x, top: it.y, blend: "over" })))
  .webp({ quality: 88, alphaQuality: 92, effort: 6, smartSubsample: true })
  .toFile(out);

const rows = items
  .map((it) => {
    const r = (n) => Number(n.toFixed(5));
    // v is measured from the bottom (textures load with flipY).
    const rect = [r(it.x / SHEET_W), r(1 - (it.y + it.h) / SHEET_H), r((it.x + it.w) / SHEET_W), r(1 - it.y / SHEET_H)];
    return `  "${it.name}": { uv: [${rect.join(", ")}], aspect: ${r(it.aspect)} },`;
  })
  .join("\n");
writeFileSync(
  DATA,
  `// Generated by scripts/optimize-stickers.mjs — do not edit.
export const STICKER_ATLAS = "/textures/stickers/atlas.webp";

/** UV rect [u0, v0, u1, v1] in the atlas and width / height of each sticker. */
export const STICKERS = {
${rows}
} as const;

export type StickerName = keyof typeof STICKERS;
export const STICKER_NAMES = Object.keys(STICKERS) as StickerName[];
`,
);
console.log(`${items.length} stickers  ${Math.round(sourceBytes / 1024 / 1024)} MB → ${Math.round(statSync(out).size / 1024)} K  (${SHEET_W}×${SHEET_H})`);
